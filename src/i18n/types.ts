export type NestedKeyOf<T> = {
  [K in keyof T & (string | number)]: T[K] extends any[]
    ? `${K}`
    : T[K] extends object
    ? `${K}` | `${K}.${NestedKeyOf<T[K]>}`
    : `${K}`;
}[keyof T & (string | number)];

export type TranslationKey = NestedKeyOf<TranslationSchema>;
